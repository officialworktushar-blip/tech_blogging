-- This script is idempotent. It is safe to run again.
-- Existing RLS policies with the same names are dropped and recreated.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text,
  sort_order integer not null default 0
);

create table if not exists public.blogs (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  subtitle text,
  slug text not null unique,
  description text,
  content text,
  category_id bigint references public.categories (id) on delete set null,
  cover_image_url text,
  cover_image_alt text,
  cover_image_note text,
  author_name text,
  status text not null default 'draft' check (status in ('draft', 'published')),
  is_featured boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  created_at timestamptz not null default now()
);

create unique index if not exists admin_users_email_lower_idx
  on public.admin_users (lower(email));

create index if not exists blogs_status_published_at_idx
  on public.blogs (status, published_at desc nulls last);

create index if not exists blogs_category_id_idx
  on public.blogs (category_id);

create index if not exists blogs_is_featured_idx
  on public.blogs (is_featured)
  where is_featured = true;

