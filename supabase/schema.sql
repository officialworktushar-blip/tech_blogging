-- 1. Open your Supabase project dashboard, then go to SQL Editor -> New query.
-- 2. Paste the entire contents of this file and click Run.
-- 3. Create your admin login under Authentication -> Users (email + password).
-- 4. Register that email as an admin by running:
--      insert into public.admin_users (email) values ('you@example.com');
-- 5. Confirm that Storage contains a public bucket named blog-images.
